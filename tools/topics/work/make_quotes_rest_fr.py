    if n not in S:
        print("MISSING", n, k); bad += 1; continue
    s, e = S[n]; verse = v["verse"]
    i = verse.find(s)
    j = verse.find(e, i) if i >= 0 else -1
    if i < 0 or j < 0:
        print("ANCHOR", n, k, repr(s), repr(e)); bad += 1; continue
    q = verse[i:j + len(e)]
    if not amq.check("fr", v["cit"], q):
        print("CHECK", n, k, q); bad += 1; continue
